use std::collections::BTreeMap;

use crate::ExperimentNode;
use crate::operation::Operation;
use crate::types::MatchTarget;
use laboneq_common::named_id::NamedIdStore;
use laboneq_error::{LabOneQError, bail};

use laboneq_common::uid::{HandleUid, PulseUid, VariableUid};
use laboneq_units::angle::Angle64;
use laboneq_units::duration::{Frequency, Hertz};

#[derive(Debug, Clone, PartialEq, Default)]
pub struct HqcsDeclarations {
    pub coprocessors: Vec<CoprocessorDecl>,
    pub mappings: Vec<CoprocessorMappingDecl>,
    pub streams: Vec<StreamDecl>,
    pub variables: Vec<VariableDecl>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct CoprocessorDecl {
    pub label: String,
    pub payload: Vec<u8>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct CoprocessorMappingDecl {
    pub label: String,
    pub inventory_key: String,
}

/// Coprocessor data is just forwarded by the compiler.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CoprocessorTable {
    /// keyed by inventory key
    pub payloads: BTreeMap<String, Vec<u8>>,
    /// label from experiment -> inventory key
    pub mappings: BTreeMap<String, String>,
}

impl TryFrom<&HqcsDeclarations> for CoprocessorTable {
    type Error = LabOneQError;

    fn try_from(value: &HqcsDeclarations) -> Result<Self, Self::Error> {
        let mut inventory_keys: BTreeMap<&str, &str> = BTreeMap::new();
        for mapping in &value.mappings {
            if inventory_keys
                .insert(&mapping.label, &mapping.inventory_key)
                .is_some()
            {
                bail!(
                    "Coprocessor '{}' is mapped to more than one inventory entry.",
                    mapping.label
                );
            }
        }

        let mut table = Self::default();
        let mut inventory_key_to_label: BTreeMap<&str, &str> = BTreeMap::new();
        for coprocessor in &value.coprocessors {
            let label = coprocessor.label.as_str();
            if table.mappings.contains_key(label) {
                bail!("Coprocessor '{label}' is declared more than once.");
            }
            let Some(&inventory_key) = inventory_keys.get(label) else {
                bail!(
                    "Coprocessor '{label}' is not mapped to an inventory entry of the \
                     device setup."
                );
            };
            if let Some(previous) = inventory_key_to_label.insert(inventory_key, label) {
                bail!(
                    "Coprocessors '{previous}' and '{label}' are both mapped to \
                     inventory entry '{inventory_key}'."
                );
            }
            table
                .mappings
                .insert(label.to_owned(), inventory_key.to_owned());
            if !coprocessor.payload.is_empty() {
                table
                    .payloads
                    .insert(inventory_key.to_owned(), coprocessor.payload.clone());
            }
        }

        if let Some(label) = inventory_keys
            .keys()
            .find(|label| !table.mappings.contains_key(**label))
        {
            bail!("Coprocessor mapping for '{label}' does not match any declared coprocessor.");
        }
        Ok(table)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StreamEndpoint {
    ControlSystem,
    /// Index into `HqcsDeclarations::coprocessors`.
    Coprocessor(u32),
}

#[derive(Debug, Clone, PartialEq)]
pub struct StreamDecl {
    /// Unique per experiment; autogenerated `stream_N` when the user did not
    /// provide one.
    pub uid: String,
    pub src: StreamEndpoint,
    pub dst: StreamEndpoint,
    pub link: Option<String>,
    pub fields: Vec<StreamFieldDecl>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct StreamFieldDecl {
    pub name: String,
    pub ty: VarType,
    pub binding: FieldBinding,
}

#[derive(Debug, Clone, PartialEq)]
pub enum FieldBinding {
    /// Outbound literal-at-send-time field, or inbound field nobody consumes.
    Unbound,
    /// Outbound acquisition field: handles feeding this field.
    Handles(Vec<HandleUid>),
    /// Inbound scalar field: variable it updates.
    Variable(VariableUid),
    /// Inbound waveform field: pulse it updates.
    Pulse(PulseUid),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VarType {
    Int8,
    Int16,
    Int32,
    Int64,
    Uint8,
    Uint16,
    Uint32,
    Uint64,
    Phase,
    Frequency,
    Amplitude,
    DiscriminationDataPacked,
    IqDataPacked,
    ScopeShot,
    WaveformUpdate,
}

#[derive(Debug, Clone, PartialEq)]
pub struct VariableDecl {
    pub ty: VarType,
    /// User-facing name for error messages; `None` when unset.
    pub name: Option<String>,
    pub initial: Option<VariableValue>,
    /// Results-capture handle; `None` = not logged.
    pub log_handle: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum VariableValue {
    Int(i64),
    Float(f64),
    Phase(Angle64),
    Frequency(Frequency<Hertz>),
    Amplitude(f64),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CmpOp {
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Predicate {
    Comparison {
        variable: VariableUid,
        op: CmpOp,
        rhs: VariableValue,
    },
    IsLive(IsLiveTarget),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum IsLiveTarget {
    Variable(VariableUid),
    Pulse(PulseUid),
}

pub fn find_hqcs_declaration(hqcs: &HqcsDeclarations) -> Option<&'static str> {
    if !hqcs.coprocessors.is_empty() {
        return Some("coprocessor handles");
    }
    if !hqcs.streams.is_empty() {
        return Some("streams");
    }
    if !hqcs.mappings.is_empty() {
        return Some("coprocessor mappings");
    }
    if !hqcs.variables.is_empty() {
        return Some("variables");
    }
    None
}

/// Describe the first HQCS construct in the tree for error messages
/// (e.g. `do_until section 'foo'`); `None` if the tree is HQCS-free.
pub fn find_hqcs_construct(node: &ExperimentNode, id_store: &NamedIdStore) -> Option<String> {
    match &node.kind {
        Operation::Send(_) => return Some("send operation".to_owned()),
        Operation::MarkStale(_) => return Some("mark_stale operation".to_owned()),
        Operation::DoUntil(do_until) => {
            let name = id_store.resolve(do_until.uid.0).unwrap_or("<unknown>");
            return Some(format!("do_until section '{name}'"));
        }
        Operation::Match(m) if matches!(m.target, MatchTarget::Variable(_)) => {
            return Some("match on a coprocessor variable".to_owned());
        }
        _ => {}
    }
    node.children
        .iter()
        .find_map(|child| find_hqcs_construct(child, id_store))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::operation::{DoUntil, MarkStale, MarkStaleTarget, Match, Operation, Send};
    use crate::types::{SectionUid, StreamUid, VariableUid};

    fn store() -> NamedIdStore {
        NamedIdStore::default()
    }

    fn decls(coprocessors: &[(&str, &[u8])], mappings: &[(&str, &str)]) -> HqcsDeclarations {
        HqcsDeclarations {
            coprocessors: coprocessors
                .iter()
                .map(|(label, payload)| CoprocessorDecl {
                    label: (*label).to_owned(),
                    payload: payload.to_vec(),
                })
                .collect(),
            mappings: mappings
                .iter()
                .map(|(label, inventory_key)| CoprocessorMappingDecl {
                    label: (*label).to_owned(),
                    inventory_key: (*inventory_key).to_owned(),
                })
                .collect(),
            ..Default::default()
        }
    }

    #[test]
    fn coprocessor_table_keys_payloads_by_inventory_key() {
        let hqcs = decls(
            &[("gpu", &[1, 2]), ("fpga", &[])],
            &[("gpu", "gpu0"), ("fpga", "fpga0")],
        );
        let table = CoprocessorTable::try_from(&hqcs).unwrap();
        assert_eq!(
            table.mappings,
            BTreeMap::from([
                ("gpu".to_owned(), "gpu0".to_owned()),
                ("fpga".to_owned(), "fpga0".to_owned()),
            ])
        );
        assert_eq!(
            table.payloads,
            BTreeMap::from([("gpu0".to_owned(), vec![1, 2])])
        );
    }

    #[test]
    fn unmapped_coprocessor_is_rejected() {
        let hqcs = decls(&[("gpu", &[1, 2])], &[]);
        let err = CoprocessorTable::try_from(&hqcs).unwrap_err().to_string();
        assert!(err.contains("'gpu' is not mapped"), "{err}");
    }

    #[test]
    fn coprocessor_mapped_twice_is_rejected() {
        let hqcs = decls(&[("gpu", &[])], &[("gpu", "gpu0"), ("gpu", "gpu1")]);
        let err = CoprocessorTable::try_from(&hqcs).unwrap_err().to_string();
        assert!(
            err.contains("'gpu' is mapped to more than one inventory entry"),
            "{err}"
        );
    }

    #[test]
    fn shared_inventory_key_is_rejected() {
        let hqcs = decls(
            &[("gpu", &[1]), ("fpga", &[2])],
            &[("gpu", "gpu0"), ("fpga", "gpu0")],
        );
        let err = CoprocessorTable::try_from(&hqcs).unwrap_err().to_string();
        assert!(
            err.contains("both mapped to inventory entry 'gpu0'"),
            "{err}"
        );
    }

    #[test]
    fn duplicate_coprocessor_label_is_rejected() {
        let hqcs = decls(&[("gpu", &[1]), ("gpu", &[2])], &[("gpu", "gpu0")]);
        let err = CoprocessorTable::try_from(&hqcs).unwrap_err().to_string();
        assert!(err.contains("'gpu' is declared more than once"), "{err}");
    }

    #[test]
    fn mapping_without_coprocessor_is_rejected() {
        let hqcs = decls(&[("gpu", &[])], &[("gpu", "gpu0"), ("ghost", "gpu1")]);
        let err = CoprocessorTable::try_from(&hqcs).unwrap_err().to_string();
        assert!(
            err.contains("'ghost' does not match any declared coprocessor"),
            "{err}"
        );
    }

    #[test]
    fn declaration_precedence_matches_tripwire_order() {
        let mut hqcs = HqcsDeclarations::default();
        assert_eq!(find_hqcs_declaration(&hqcs), None);
        hqcs.variables.push(VariableDecl {
            ty: VarType::Int32,
            name: None,
            initial: None,
            log_handle: None,
        });
        assert_eq!(find_hqcs_declaration(&hqcs), Some("variables"));
        hqcs.coprocessors.push(CoprocessorDecl {
            label: "gpu".into(),
            payload: vec![],
        });
        assert_eq!(find_hqcs_declaration(&hqcs), Some("coprocessor handles"));
    }

    #[test]
    fn finds_nested_hqcs_construct() {
        let mut id_store = store();
        let uid = SectionUid(id_store.get_or_insert("wait"));
        let mut root = ExperimentNode::new(Operation::Root);
        let mut section = ExperimentNode::new(Operation::DoUntil(DoUntil {
            uid,
            condition: Predicate::IsLive(IsLiveTarget::Variable(VariableUid(0))),
            max_count: 1,
        }));
        section
            .children
            .push(ExperimentNode::new(Operation::MarkStale(MarkStale {
                target: MarkStaleTarget::Variable(VariableUid(0)),
            })));
        root.children.push(section);
        assert_eq!(
            find_hqcs_construct(&root, &id_store),
            Some("do_until section 'wait'".to_owned())
        );
    }

    #[test]
    fn hqcs_free_tree_yields_none() {
        let root = ExperimentNode::new(Operation::Root);
        assert_eq!(find_hqcs_construct(&root, &store()), None);
    }

    #[test]
    fn finds_send_and_match_variable() {
        let mut id_store = store();
        let stream = StreamUid(id_store.get_or_insert("s0"));
        let mut root = ExperimentNode::new(Operation::Root);
        root.children
            .push(ExperimentNode::new(Operation::Send(Send {
                stream,
                args: vec![],
            })));
        assert_eq!(
            find_hqcs_construct(&root, &id_store),
            Some("send operation".to_owned())
        );

        let uid = SectionUid(id_store.get_or_insert("m"));
        let mut root = ExperimentNode::new(Operation::Root);
        root.children
            .push(ExperimentNode::new(Operation::Match(Match {
                uid,
                target: MatchTarget::Variable(VariableUid(0)),
                local: None,
                play_after: vec![],
            })));
        assert_eq!(
            find_hqcs_construct(&root, &id_store),
            Some("match on a coprocessor variable".to_owned())
        );
    }
}
